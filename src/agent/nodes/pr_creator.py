"""Node 11: open the pull request (one per ``{cve_id, repo}``; the bot never merges)."""

from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Any

import structlog

from src.agent.deps import get_idempotency_store, get_pr_service, get_tier_thresholds
from src.agent.nodes._common import NodeError, agent_node, make_event
from src.agent.state import AgentState
from src.core.config import settings
from src.services.github.codeowners import split_owners
from src.services.github.pr_creator import PRConflictError
from src.services.github.pr_description import DEFAULT_HIGH, DEFAULT_MEDIUM, one_line, pr_title, render_pr_body

log = structlog.get_logger(__name__)

_CVE_RE = re.compile(r"^CVE-\d{4}-\d{4,}$")


def branch_name(state: AgentState, today: datetime | None = None) -> str:
    """``fix/cve-{CVE_ID}-{repo}-{YYYYMMDD}`` with the repo name reduced to ref-safe characters."""
    if not _CVE_RE.match(state.cve_id):
        raise NodeError(f"refusing to build a branch name from malformed CVE id {state.cve_id!r}")
    short = re.sub(r"[^A-Za-z0-9._-]+", "-", state.repo_name.split("/")[-1]).strip("-.") or "repo"
    day = (today or datetime.now(timezone.utc)).strftime("%Y%m%d")
    return f"{settings.PR_BRANCH_PREFIX}{state.cve_id}-{short}-{day}"


async def _tier_thresholds() -> tuple[int, int]:
    """Calibrated confidence-tier cut-offs; the defaults if calibration data is unavailable."""
    try:
        return await get_tier_thresholds()()
    except Exception as exc:  # noqa: BLE001 - cosmetic input, never block a PR on it
        log.warning("create_pr.thresholds_unavailable", error=str(exc))
        return DEFAULT_HIGH, DEFAULT_MEDIUM


def _result_update(state: AgentState, pr: dict[str, Any], status: str, owners: list[str], extra_event: dict[str, Any]) -> dict[str, Any]:
    event = "PR_RAISED" if status == "PR_RAISED" else "PR_DEDUPLICATED"
    return {
        "branch_name": pr["branch"],
        "pr_url": pr["url"],
        "pr_number": pr["number"],
        "terminal_status": status,
        "code_owners": owners,
        "pr_warnings": pr.get("warnings", []),
        "audit_events": [*state.audit_events, make_event(event, {**pr, **extra_event})],
    }


@agent_node("create_pr")
async def create_pr(state: AgentState) -> dict[str, Any]:
    """Create the branch, commit, PR, labels and review requests.

    Idempotent: a recorded result for this ``job_id`` is replayed, and an open bot PR for the same CVE
    in the repo is never duplicated (another job's PR ends the run as ``PR_EXISTS``).
    """
    if not state.file_changes:
        raise NodeError("create_pr requires file changes")
    svc, idem = get_pr_service(), get_idempotency_store()
    key = f"create_pr:{state.job_id}"

    if (prior := await idem.get(key)) is not None:
        log.info("create_pr.replayed", pr_url=prior["url"])
        return _result_update(state, prior, "PR_RAISED", prior.get("owners", []), {"replayed": True})

    existing = await svc.find_open_pr(state.repo_name, state.cve_id, settings.PR_BRANCH_PREFIX)
    if existing is not None:
        pr = {"url": existing.url, "number": existing.number, "branch": existing.branch}
        if existing.job_id == state.job_id:  # we created it, then crashed before recording the key
            await idem.put(key, "create_pr", pr)
            return _result_update(state, pr, "PR_RAISED", [], {"recovered": True})
        log.info("create_pr.deduplicated", existing=existing.url, existing_job=existing.job_id)
        return _result_update(state, pr, "PR_EXISTS", [], {"existing_job_id": existing.job_id})

    paths = [c.file_path for c in state.file_changes]
    owners = await svc.get_code_owners(state.repo_name, paths)
    users, teams, _emails = split_owners(owners)
    protection = await svc.branch_protection(state.repo_name)
    if protection.get("protected") is False:
        log.warning("create_pr.default_branch_unprotected", repo=state.repo_name)

    labels = [*settings.PR_LABELS, f"severity:{state.severity.lower()}"]
    try:
        result = await svc.create_pr(
            repo=state.repo_name,
            branch=branch_name(state),
            title=pr_title(state),
            body=render_pr_body(state, settings.CONTROL_API_URL, await _tier_thresholds()),
            commit_message=(
                f"fix({state.cve_id}): bump {one_line(state.affected_package)} "
                f"{one_line(state.installed_version)} -> {one_line(state.target_version)}\n\n"
                f"Automated security fix generated by the CVE Auto-Remediation Platform (job {state.job_id})."
            ),
            changes=state.file_changes,
            labels=labels,
            users=users,
            teams=teams,
        )
    except PRConflictError as exc:
        raise NodeError(f"cannot raise PR: {exc}") from exc

    pr = {
        "url": result.url, "number": result.number, "branch": result.branch, "labels": result.labels,
        "reviewers": result.reviewers, "warnings": result.warnings, "owners": owners,
    }  # fmt: skip
    await idem.put(key, "create_pr", pr)
    return _result_update(
        state, pr, "PR_RAISED", owners,
        {"base_branch": result.base_branch, "branch_protection": protection, "confidence_score": state.confidence_score},
    )  # fmt: skip
